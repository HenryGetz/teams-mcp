/**
 * Tool + resource registry: the entire model-facing surface.
 *
 * Seven tools, each with an `op` enum, so the schema tokens an MCP client has to
 * load stay small while new operations add no new tools. See docs/design.md.
 *
 * One optional resource exposes the newest calendar snapshot so a client can read
 * it without spending a tool call; every tool remains self-sufficient.
 */
import { readFile } from "node:fs/promises";
import type { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import type { CallToolResult } from "@modelcontextprotocol/sdk/types.js";
import { authTool } from "./auth.js";
import { mailTool } from "./mail.js";
import { calendarTool } from "./calendar.js";
import { availabilityTool } from "./availability.js";
import { peopleTool } from "./people.js";
import { settingsTool } from "./settings.js";
import { teamsTool } from "./teams.js";
import type { ToolModule } from "./shared.js";
import { readSnapshot, snapshotPath } from "../snapshot/calendar.js";

export const TOOL_MODULES: readonly ToolModule[] = [
  authTool,
  mailTool,
  calendarTool,
  availabilityTool,
  peopleTool,
  settingsTool,
  teamsTool,
];

export const SNAPSHOT_RESOURCE_URI = "teams-mcp://calendar/snapshot";

/** Register every tool on a server. Returns the registered names. */
export function registerTools(server: McpServer): string[] {
  for (const module of TOOL_MODULES) {
    server.registerTool(
      module.name,
      {
        title: module.title,
        description: module.description,
        inputSchema: module.shape,
      },
      async (args): Promise<CallToolResult> => module.handle(args as Record<string, unknown>),
    );
  }
  return TOOL_MODULES.map((module) => module.name);
}

/** Register the read-only snapshot resource. */
export function registerResources(server: McpServer): string[] {
  server.registerResource(
    "calendar-snapshot",
    SNAPSHOT_RESOURCE_URI,
    {
      title: "Calendar snapshot",
      description:
        "Full teams-mcp calendar snapshot as YAML (metadata, own events and per-attendee busy blocks; can be ~10 KB) for bulk planning. For one scheduling question prefer availability.freebusy/suggest, which return compact summaries. Regenerated by availability op=snapshot.",
      mimeType: "application/yaml",
    },
    async (uri) => {
      const path = snapshotPath();
      const loaded = await readSnapshot(path);
      if (!loaded) {
        throw new Error(
          `no calendar snapshot at ${path}; run availability op=snapshot to create one`,
        );
      }
      const text = await readFile(loaded.path, "utf8");
      return { contents: [{ uri: uri.href, mimeType: "application/yaml", text }] };
    },
  );
  return [SNAPSHOT_RESOURCE_URI];
}
